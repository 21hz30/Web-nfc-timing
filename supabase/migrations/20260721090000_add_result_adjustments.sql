create table if not exists public.result_adjustments (
  id bigint generated by default as identity primary key,
  race_id text not null,
  participant_id bigint not null references public.participants(id) on delete cascade,
  adjustment_ms integer not null,
  reason text not null,
  created_at timestamptz not null default timezone('utc', now()),
  constraint result_adjustments_nonzero_check check (adjustment_ms <> 0),
  constraint result_adjustments_range_check
    check (adjustment_ms between -86400000 and 86400000),
  constraint result_adjustments_reason_check
    check (char_length(btrim(reason)) between 2 and 500)
);

alter table public.race_profiles
  add column if not exists status text not null default 'active',
  add column if not exists finalized_at timestamptz;

alter table public.race_profiles
  drop constraint if exists race_profiles_status_check;

alter table public.race_profiles
  add constraint race_profiles_status_check check (status in ('active', 'finalized'));

create index if not exists result_adjustments_race_participant_idx
  on public.result_adjustments (race_id, participant_id, created_at, id);

alter table public.result_adjustments enable row level security;

revoke all on public.result_adjustments from anon, authenticated;
grant select, insert, update on public.result_adjustments to anon;

create policy result_adjustments_server_select
  on public.result_adjustments
  for select
  to anon
  using ((select private.timing_api_authorized()));

create policy result_adjustments_server_insert
  on public.result_adjustments
  for insert
  to anon
  with check ((select private.timing_api_authorized()));

create policy result_adjustments_server_update
  on public.result_adjustments
  for update
  to anon
  using ((select private.timing_api_authorized()))
  with check ((select private.timing_api_authorized()));
