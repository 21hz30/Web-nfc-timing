create table if not exists public.manual_results (
  id bigint generated by default as identity primary key,
  race_id text not null,
  participant_id bigint not null references public.participants(id) on delete cascade,
  entry_mode text not null,
  start_time timestamptz,
  finish_time timestamptz,
  elapsed_ms integer not null,
  reason text not null,
  created_at timestamptz not null default timezone('utc', now()),
  constraint manual_results_entry_mode_check
    check (entry_mode in ('start_finish', 'elapsed')),
  constraint manual_results_elapsed_check
    check (elapsed_ms between 0 and 86400000),
  constraint manual_results_times_check
    check (
      (entry_mode = 'elapsed' and start_time is null and finish_time is null)
      or
      (entry_mode = 'start_finish' and start_time is not null and finish_time is not null
        and finish_time >= start_time)
    ),
  constraint manual_results_reason_check
    check (char_length(btrim(reason)) between 2 and 500)
);

create index if not exists manual_results_race_participant_idx
  on public.manual_results (race_id, participant_id, created_at desc, id desc);

create table if not exists public.participant_timing_controls (
  id bigint generated by default as identity primary key,
  race_id text not null,
  participant_id bigint not null references public.participants(id) on delete cascade,
  action text not null,
  reason text not null,
  created_at timestamptz not null default timezone('utc', now()),
  constraint participant_timing_controls_action_check
    check (action in ('pause', 'resume', 'dnf', 'restore')),
  constraint participant_timing_controls_reason_check
    check (char_length(btrim(reason)) between 2 and 500)
);

create index if not exists participant_timing_controls_race_participant_idx
  on public.participant_timing_controls (race_id, participant_id, created_at, id);

alter table public.manual_results enable row level security;
alter table public.participant_timing_controls enable row level security;

revoke all on public.manual_results, public.participant_timing_controls from anon, authenticated;
grant select, insert, update on public.manual_results, public.participant_timing_controls to anon;

create policy manual_results_server_select
  on public.manual_results for select to anon
  using ((select private.timing_api_authorized()));

create policy manual_results_server_insert
  on public.manual_results for insert to anon
  with check ((select private.timing_api_authorized()));

create policy manual_results_server_update
  on public.manual_results for update to anon
  using ((select private.timing_api_authorized()))
  with check ((select private.timing_api_authorized()));

create policy participant_timing_controls_server_select
  on public.participant_timing_controls for select to anon
  using ((select private.timing_api_authorized()));

create policy participant_timing_controls_server_insert
  on public.participant_timing_controls for insert to anon
  with check ((select private.timing_api_authorized()));

create policy participant_timing_controls_server_update
  on public.participant_timing_controls for update to anon
  using ((select private.timing_api_authorized()))
  with check ((select private.timing_api_authorized()));

